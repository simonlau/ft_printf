#include "libft.h"
#include <stdlib.h>

t_list	*ft_lstnew(void *content)
{
	t_list	*node_ptr;

	node_ptr = malloc(sizeof(*node_ptr));
	if (node_ptr == NULL)
	{
		return (NULL);
	}
	node_ptr->content = content;
	node_ptr->next = NULL;
	return (node_ptr);
}
